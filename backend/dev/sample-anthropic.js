function freeGunghab(p) {
  const label = firstMatch(p, /^\[관계\] (.+)$/m);
  const rel = REL[label];
  if (!rel) return BANNER + '===한 줄 요약===\n(예시 서버가 모르는 관계 유형이에요.)';
  const role = firstMatch(p, /읽는 사람은 .+?님\((부모|자녀)\)/);
  const bars = [...p.matchAll(/^\d\. (.+?) — .+? → 이 항목의 수준은 '(.+?)'으로/gm)].map(m => ({ label: m[1], level: m[2] }));
  const barText = bars.map(b => {
    const [focus, tip] = rel.bars[b.label] || ['이 항목은', '오늘 한 가지를 정해 해보세요.'];
    return `===${b.label}===\n해설: ${focus} ${TAIL[b.level] || TAIL['무난한 편']}\n팁: ${typeof tip === 'string' ? tip : tip[role] || tip['부모']}`;
  }).join('\n\n');
  const line = rel.line || rel.lineByRole[role] || rel.lineByRole['부모'];
  return `${BANNER}===한 줄 요약===\n${rel.headline}\n\n===관계 요약===\n${rel.summary}\n\n${barText}\n\n===잘 맞는 점===\n${rel.good}\n\n===조율할 점===\n${rel.tune}\n\n===대화 문장===\n${line}`;
}

