const 천간한자 = ['甲','乙','丙','丁','戊','己','庚','辛','壬','癸'];
const 지지한자 = ['子','丑','寅','卯','辰','巳','午','未','申','酉','戌','亥'];
const 간오행 = { 甲:'목', 乙:'목', 丙:'화', 丁:'화', 戊:'토', 己:'토', 庚:'금', 辛:'금', 壬:'수', 癸:'수' };
const 지오행 = { 子:'수', 丑:'토', 寅:'목', 卯:'목', 辰:'토', 巳:'화', 午:'화', 未:'토', 申:'금', 酉:'금', 戌:'토', 亥:'수' };
const 상생 = { 목:'화', 화:'토', 토:'금', 금:'수', 수:'목' };
const 상극 = { 목:'토', 토:'수', 수:'화', 화:'금', 금:'목' };
const 육합 = [['子','丑'],['寅','亥'],['卯','戌'],['辰','酉'],['巳','申'],['午','未']];
const 충 = [['子','午'],['丑','未'],['寅','申'],['卯','酉'],['辰','戌'],['巳','亥']];

const parse간지 = (s) => (!s || s === '-') ? { 간: null, 지: null } : { 간: 천간한자.find(c => s.includes(c)) || null, 지: 지지한자.find(c => s.includes(c)) || null };
const inPair = (pairs, a, b) => pairs.some(p => (p[0] === a && p[1] === b) || (p[1] === a && p[0] === b));
const elementLevel = (a, b) => (!a || !b) ? 'mid' : (상생[a] === b || 상생[b] === a) ? 'high' : (상극[a] === b || 상극[b] === a) ? 'low' : 'mid';

// saju1, saju2: { 일주, 월주 } (calcSaju 결과). 반환: 바 3개 순서의 수준 키 배열.
function calcRelationLevels(saju1, saju2) {
  const a일 = parse간지(saju1.일주), b일 = parse간지(saju2.일주);
  const a월 = parse간지(saju1.월주), b월 = parse간지(saju2.월주);
  // 일간: 서로 생해 주면 high, 극하면 low, 같은 오행이거나 관계가 없으면 mid
  const 기질 = elementLevel(a일.간 && 간오행[a일.간], b일.간 && 간오행[b일.간]);
  // 일지: 충이면 low, 합이거나 생해 주면 high, 극하면 low, 그 외 mid
  let 일지 = 'mid';
  if (a일.지 && b일.지) {
    if (inPair(충, a일.지, b일.지)) 일지 = 'low';
    else if (inPair(육합, a일.지, b일.지)) 일지 = 'high';
    else 일지 = elementLevel(지오행[a일.지], 지오행[b일.지]);
  }
  // 월지: 생해 주면 high, 극하면 low
  const 월지 = elementLevel(a월.지 && 지오행[a월.지], b월.지 && 지오행[b월.지]);
  return [기질, 일지, 월지];
}

// 클라이언트에 보낼 바 정보 (라벨 + 수준). 해설·팁은 AI가 채운다.
// 두 사람의 일간(기질)·일지·월지가 만나는 방식의 "근거" 문장. AI는 이 근거와 계산값 표에 있는 관계만 설명할 수 있다.
function relPhrase(a, b) {
  const A = 쉬운오행[a], B = 쉬운오행[b];
  if (a === b) return `${A} 기운끼리 같아서 닮은 면이 있는 관계`;
  if (상생[a] === b) return `${A} 기운이 ${B} 기운을 키워주는 관계(상생)`;
  if (상생[b] === a) return `${B} 기운이 ${A} 기운을 키워주는 관계(상생)`;
  if (상극[a] === b) return `${A} 기운이 ${B} 기운을 누르는 관계(상극)`;
  if (상극[b] === a) return `${B} 기운이 ${A} 기운을 누르는 관계(상극)`;
  return `${A} 기운과 ${B} 기운은 직접 키워주거나 누르는 관계가 아님`;
}
function calcRelationBasis(saju1, saju2) {
  const a일 = parsePillar(saju1.일주), b일 = parsePillar(saju2.일주);
  const a월 = parsePillar(saju1.월주), b월 = parsePillar(saju2.월주);
  const none = '계산할 수 없어 근거 없음';
  const 기질 = a일 && b일 ? `일간 ${a일.gan}(읽는 사람)과 ${b일.gan}(상대): ${relPhrase(간오행[a일.gan], 간오행[b일.gan])}` : none;
  let 일지 = none;
  if (a일 && b일) {
    일지 = `일지 ${a일.ji}과 ${b일.ji}: ` + (inPair(충, a일.ji, b일.ji) ? '서로 부딪히기 쉬운 짝(충)' : inPair(육합, a일.ji, b일.ji) ? '서로 어울려 묶이는 짝(육합)' : relPhrase(지오행[a일.ji], 지오행[b일.ji]));
  }
  const 월지 = a월 && b월 ? `월지 ${a월.ji}과 ${b월.ji}: ${relPhrase(지오행[a월.ji], 지오행[b월.ji])}` : none;
  return [기질, 일지, 월지];
}

