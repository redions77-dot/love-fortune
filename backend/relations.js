function roleBlock(relKey, role, nameA, nameB) {
  if (!RELATIONS[relKey].needsRole) return '';
  const [parent, child] = role === '부모' ? [nameA, nameB] : [nameB, nameA];
  return `\n[역할] ${parent}님이 부모, ${child}님이 자녀입니다. 읽는 사람은 ${nameA}님(${role})입니다. 조언과 대화 문장은 ${nameA}님(${role})이 상대에게 건네는 말로 쓰세요.`;
}

