const LEGACY_ALIASES = Object.freeze({ 가족: '형제가족', 직장상사: '직장동료' });
const ROLES = ['부모', '자녀'];

// 유효하면 { key, role }, 아니면 null. role 은 부모·자녀 관계에서만 의미가 있다.
function normalizeRelation(raw, rawRole) {
  const key = LEGACY_ALIASES[raw] || raw;
  const def = RELATIONS[key];
  if (!def) return null;
  if (def.needsRole) {
    if (!ROLES.includes(rawRole)) return null;
    return { key, role: rawRole };
  }
  return { key, role: '' };
}

